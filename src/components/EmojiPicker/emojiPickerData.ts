/** Curated default set for Storybook / demos — extend or replace via props. */
export type EmojiPickerItem = {
  /** Unicode scalar sequence as a JS string */
  char: string
  /** Lowercase ASCII keywords for search (no spaces required in query) */
  keywords: string[]
}

export type EmojiPickerCategory = {
  id: string
  label: string
  emojis: EmojiPickerItem[]
}

function e(char: string, ...keywords: string[]): EmojiPickerItem {
  return { char, keywords: keywords.map((k) => k.toLowerCase()) }
}

